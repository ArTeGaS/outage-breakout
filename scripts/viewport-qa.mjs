import {createRequire} from 'node:module';
import {mkdir,writeFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const browser=await chromium.launch({headless:true,...(process.env.CHROMIUM_PATH?{executablePath:process.env.CHROMIUM_PATH}:{})});
const base=process.env.QA_URL||'http://127.0.0.1:4173',out='output/viewport-qa';
await mkdir(out,{recursive:true});const result={};
try {
  const context=await browser.newContext({viewport:{width:360,height:800},deviceScaleFactor:1,isMobile:true,hasTouch:true});
  const page=await context.newPage(),errors=[];
  page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
  await page.goto(`${base}/?skin=kyiv&theme=dark`);await page.evaluate(()=>document.fonts.ready);
  let position=await page.evaluate(()=>{const a=document.querySelector('#overlay').getBoundingClientRect(),b=document.querySelector('#game').getBoundingClientRect();return {overlay:a.top+a.height/2,game:b.top+b.height/2}});
  assert.ok(Math.abs(position.overlay-position.game)<2,'start is not centered');
  await page.screenshot({path:`${out}/start.png`});
  await page.locator('#start').tap();await page.evaluate(()=>advanceTime(0));
  const initial=JSON.parse(await page.evaluate(()=>render_game_to_text()));assert.equal(initial.mode,'playing');
  await page.setViewportSize({width:360,height:689});await page.waitForTimeout(80);
  let previous=JSON.parse(await page.evaluate(()=>render_game_to_text()));
  assert.equal(previous.mode,'playing');assert.equal(previous.score,initial.score);assert.equal(previous.lives,initial.lives);
  assert.deepEqual(previous.ball,initial.ball,'viewport change moved a live ball');
  let fitted=previous.height<initial.height;
  for(let i=0;i<80&&!fitted;i++) {
    await page.evaluate(()=>advanceTime(16));await page.waitForTimeout(20);
    const current=JSON.parse(await page.evaluate(()=>render_game_to_text()));
    assert.equal(current.mode,'playing');assert.equal(current.score,initial.score);assert.equal(current.lives,initial.lives);
    const delta=Math.hypot(current.ball.x-previous.ball.x,current.ball.y-previous.ball.y);
    assert.ok(delta<12,`ball jumped ${delta}px during viewport resize`);
    fitted=current.height<initial.height;previous=current;
  }
  assert.ok(fitted,'height did not adapt after the ball moved away from the paddle');
  const bounds=await page.evaluate(()=>{const box=s=>{const r=document.querySelector(s).getBoundingClientRect();return {top:r.top,bottom:r.bottom}};return {height:innerHeight,game:box('.game-shell'),legend:box('.below-game'),footer:box('footer')}});
  assert.ok(bounds.game.bottom<=bounds.height-1&&bounds.legend.bottom<=bounds.height-1&&bounds.footer.bottom<=bounds.height-1,JSON.stringify(bounds));
  const gameBox=await page.locator('#game').boundingBox(),cdp=await context.newCDPSession(page);
  const touchY=gameBox.y+gameBox.height-24;
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:gameBox.x+40,y:touchY}]});
  const left=JSON.parse(await page.evaluate(()=>render_game_to_text())).paddle.x;
  for(let i=1;i<=10;i++)await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:gameBox.x+40+(gameBox.width-80)*i/10,y:touchY}]});
  const right=JSON.parse(await page.evaluate(()=>render_game_to_text())).paddle.x;
  await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
  assert.ok(right-left>gameBox.width/2,'touch drag did not move the paddle');
  await page.waitForTimeout(350);
  await page.screenshot({path:`${out}/playing-resized.png`});
  await page.locator('#pause').click();
  await page.waitForFunction(()=>JSON.parse(render_game_to_text()).mode==='paused',null,{timeout:2000});
  position=await page.evaluate(()=>{const a=document.querySelector('#overlay').getBoundingClientRect(),b=document.querySelector('#game').getBoundingClientRect();return {overlay:a.top+a.height/2,game:b.top+b.height/2}});
  assert.ok(Math.abs(position.overlay-position.game)<2,`resume is not centered: ${JSON.stringify(position)}`);
  await page.screenshot({path:`${out}/pause.png`});
  await page.locator('#start').click();await page.evaluate(()=>advanceTime(0));
  assert.equal(JSON.parse(await page.evaluate(()=>render_game_to_text())).mode,'playing');
  await page.locator('#fullscreen').click();await page.waitForTimeout(200);
  assert.equal(await page.evaluate(()=>!!document.fullscreenElement),true,'fullscreen did not open');
  const full=await page.evaluate(()=>{const a=document.querySelector('.status-bar').getBoundingClientRect(),b=document.querySelector('#game').getBoundingClientRect();return {top:a.top,bottom:b.bottom,height:innerHeight}});
  assert.ok(full.top>=-1&&full.bottom<=full.height+1,`fullscreen cropped: ${JSON.stringify(full)}`);
  await page.screenshot({path:`${out}/fullscreen.png`});await page.evaluate(()=>document.exitFullscreen());
  assert.deepEqual(errors,[]);Object.assign(result,{initialHeight:initial.height,afterHeight:previous.height,bounds,fullscreen:full,touchDrag:{left,right},mode:'playing during resize',errors});
  await context.close();
  const touchContext=await browser.newContext({viewport:{width:360,height:689},deviceScaleFactor:1,isMobile:true,hasTouch:true});
  const touchPage=await touchContext.newPage();await touchPage.goto(`${base}/?skin=kyiv&theme=dark`);
  await touchPage.locator('#start').tap();await touchPage.waitForFunction(()=>JSON.parse(render_game_to_text()).mode==='playing');
  await touchPage.evaluate(()=>advanceTime(0));
  const box=await touchPage.locator('#game').boundingBox(),touchCdp=await touchContext.newCDPSession(touchPage),y=box.y+box.height-24;
  await touchCdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:box.x+40,y}]});
  for(let i=1;i<=10;i++)await touchCdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:box.x+40+(box.width-80)*i/10,y}]});
  await touchCdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
  await touchPage.waitForTimeout(300);await touchPage.locator('#pause').tap();
  await touchPage.waitForFunction(()=>JSON.parse(render_game_to_text()).mode==='paused',null,{timeout:2500});
  await touchPage.locator('#start').tap();await touchPage.waitForFunction(()=>JSON.parse(render_game_to_text()).mode==='playing',null,{timeout:2500});
  result.touchPauseResume='passed';await touchContext.close();
  await writeFile(`${out}/results.json`,JSON.stringify(result,null,2));console.log(JSON.stringify(result,null,2));
} finally {await browser.close()}
